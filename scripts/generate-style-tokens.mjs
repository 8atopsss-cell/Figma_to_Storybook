import fs from 'node:fs';
import { compileStyles } from './compile-styles.mjs';
const source = JSON.parse(fs.readFileSync('source/figma/styles-export.json', 'utf8'));
const tokens = compileStyles(source);
fs.writeFileSync('src/tokens/styles.json', JSON.stringify(tokens, null, 2) + '\n');
const lines = ['/* Generated by npm run tokens from local Figma styles. Do not edit. */', ':root {'];
for (const color of tokens.colors) lines.push('  ' + color.cssVariable + ': ' + color.value + ';');
for (const text of tokens.typography) for (const [field, value] of Object.entries(text.css)) lines.push('  --figma-' + text.key + '-' + field + ': ' + value + ';');
lines.push('}');
for (const text of tokens.typography) {
  lines.push('.' + text.className + ' {');
  for (const field of Object.keys(text.css).filter(field => !['paragraph-spacing', 'list-spacing'].includes(field))) lines.push('  ' + field + ': var(--figma-' + text.key + '-' + field + ');');
  lines.push('}');
  lines.push('.' + text.className + ' > p { margin: 0; }');
  lines.push('.' + text.className + ' > p + p { margin-top: var(--figma-' + text.key + '-paragraph-spacing); }');
  lines.push('.' + text.className + ' li + li { margin-top: var(--figma-' + text.key + '-list-spacing); }');
}
fs.writeFileSync('src/styles/figma-styles.css', lines.join('\n') + '\n');
console.log('Exported ' + tokens.colors.length + ' color styles and ' + tokens.typography.length + ' text styles.');
